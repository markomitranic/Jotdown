import type { ComponentType, ReactNode } from "react";
import { DocsBody, DocsDescription, DocsTitle } from "@jotdown/core/components/docs/page";
import FigureStage from "@jotdown/core/components/blocks/FigureStage";
import { resolvePageIcon } from "@jotdown/core/lib/page-icon";

type Props = {
  title: string;
  description?: string;
  /** A Lucide name from the page's front matter. */
  icon?: string;
  /** Code owns the page, so it wears the two read-only badges. */
  generated?: boolean;
  /** Draws the description even when the page has none, so an editor has somewhere to write one. */
  editable?: boolean;
  /** The front matter fields, for an app that edits them in place; read-only otherwise. */
  fields?: Fields;
  /** The compiled article. */
  children: ReactNode;
};

/** How the three front matter fields are drawn. */
export type Fields = {
  Title: ComponentType<{ children: string }>;
  Description: ComponentType<{ children?: string }>;
  Icon: ComponentType<{ name?: string; children: ReactNode }>;
};

const READING: Fields = {
  Title: ({ children }) => children,
  Description: ({ children }) => children,
  Icon: ({ children }) =>
    children ? (
      <span className="shrink-0 [&_svg]:size-7" aria-hidden="true">
        {children}
      </span>
    ) : null,
};

/**
 * A page's heading, lead and article, the way every page is drawn.
 *
 * The route decides what the page is and whether it can be edited; this is
 * only how it looks, so a page rendered anywhere else reads exactly like one
 * the route served. The article underneath is handed in already compiled.
 *
 * @example <PageContent title="Intro"><MDX /></PageContent>
 */
export function PageContent({
  title,
  description,
  icon,
  generated,
  editable = false,
  fields = READING,
  children,
}: Props) {
  const { Title, Description, Icon } = fields;
  const writable = editable || description !== undefined;

  return (
    <>
      {generated && <GeneratedBadges />}

      <DocsTitle className="group/title relative flex items-center gap-3 pr-40">
        <Icon name={icon}>{resolvePageIcon(icon)}</Icon>
        <Title>{title}</Title>
      </DocsTitle>

      <DocsDescription className="mb-4">
        {writable ? <Description>{description}</Description> : undefined}
      </DocsDescription>

      <DocsBody className="wrap-break-word">
        {children}
        <FigureStage />
      </DocsBody>
    </>
  );
}

function GeneratedBadges() {
  return (
    <div className="mb-3 flex gap-2" title="This page is generated by code. Manual edits would be overwritten.">
      <span className="rounded border px-2 py-0.5 text-muted-foreground text-xs">generated</span>
      <span className="rounded border px-2 py-0.5 text-muted-foreground text-xs">read-only</span>
    </div>
  );
}
