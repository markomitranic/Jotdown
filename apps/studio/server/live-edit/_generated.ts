import { parse } from "yaml";

/**
 * Refuses writes to generated pages, using the stored front matter rather than submitted text.
 *
 * Front matter that will not parse is refused only when it names `generated`,
 * so a page an agent broke can still be fixed from the studio.
 * @example pageWriteRefusal("docs/api.mdx", "---\ngenerated: true\n---\n"); // a refusal
 */
export function pageWriteRefusal(path: string, source: string): string | null {
  const header = /^\uFEFF?---[ \t]*\r?\n([\s\S]*?)\r?\n---[ \t]*(?:\r?\n|$)/.exec(source)?.[1];
  if (header === undefined) return null;

  try {
    const fields: unknown = parse(header);
    if (fields && typeof fields === "object" && "generated" in fields && fields.generated === true) {
      return `${path} is generated by code and is read-only. Change its generator instead.`;
    }
    return null;
  } catch {
    return /^["']?generated["']?[ \t]*:/im.test(header)
      ? `${path} has invalid front matter and may be generated. Fix it in the repository.`
      : null;
  }
}
